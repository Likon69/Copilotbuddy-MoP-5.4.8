		internal static bool IsElite(this WoWUnit unit)
		{
			if (!unit.IsValid)
				return false;

			if (unit.CreatureRank == WoWUnitClassificationType.Elite)
				return true;

			if (unit.CreatureRank == WoWUnitClassificationType.RareElite)
				return true;

			if (unit.CreatureRank == WoWUnitClassificationType.WorldBoss)
				return true;

			return false;
		}
	}

