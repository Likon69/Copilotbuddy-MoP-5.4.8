        private static string GatherbuddyAvoidListPath
	    {
	        get
	        {
	            return Path.Combine(Path.Combine(Path.Combine(SettingsDirectory, StyxWoW.Me.RealmName), StyxWoW.Me.Name),
                                    "GatherbuddyAvoidList.xml");
	        }
	    }

		private static void LoadAvoidList()
		{
            if (!File.Exists(GatherbuddyAvoidListPath))
			{
				SaveAvoidList();
				return;
			}

            nodeAvoidList = (from e in XElement.Load(GatherbuddyAvoidListPath).Elements("Avoid") select uint.Parse(e.Value)).ToList();
		}

		internal static void SaveAvoidList()
		{
			XDocument xmlFile = new XDocument(
									new XComment("This xml document is generated by Gatherbuddy."),
									new XComment("DO NOT EDIT THIS FILE. USE SETTINGS FORM INSTEAD"),
									new XElement("GBAvoidList",
										from i in nodeAvoidList
										select new XElement("Avoid",
											new XText(i.ToString()))));

            xmlFile.Save(GatherbuddyAvoidListPath);
		}

