		private static bool ShouldMail(WoWItem item)
		{
			if (ProfileManager.CurrentProfile == null)
				return false;

			var curProfile = ProfileManager.CurrentProfile;

			if (curProfile.ForceMail.HashSet1.Contains(item.Entry))
				return true;

			if (curProfile.ForceMail.HashSet2.Contains(item.Name))
				return true;

			//Gnomish Army Knife
			if (item.Entry == 40772)
				return false;

			if (item.IsSoulbound)
				return false;

			if (item.Quality == WoWItemQuality.Heirloom)
				return false;

			if (item.IsConjured)
				return false;

            //if (item.Duration != 0)
            //    return false;

            if (item.IsAccountBound)
                return false;

            if (item.ItemInfo.ItemClass == WoWItemClass.Key)
                return false;

            if (item.ItemInfo.Bond == WoWItemBondType.Quest)
                return false;

            if (item.ItemInfo.BeginQuestId != 0)
                return false;

			if (item.ItemInfo.ItemClass == WoWItemClass.Consumable)
				return false;

			if (curProfile.ProtectedItems.Contains(item.Entry))
				return false;

			if (!curProfile.MailQualities.Contains(item.Quality))
				return false;

			return true;
		}

